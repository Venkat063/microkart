"""Scaffolds missing services, docker-compose.yml, infra configs and the chart's service list from services.yaml.
Never overwrites a service that already has hand-written code."""
from pathlib import Path
from registry import ROOT, load

SKELETON = '''"""{name} ({domain}) - scaffold. Replace with real logic; keep create_app()."""
from microkart_common import create_app

app = create_app("{name}", "{domain}")


@app.get("/")
def root():
    return {{"service": "{name}", "domain": "{domain}", "status": "scaffold", "phase": {phase}}}
'''


def main():
    services = load()
    created = 0
    for s in services:
        main_py = ROOT / "services" / s["name"] / "main.py"
        if not main_py.exists():
            main_py.parent.mkdir(parents=True, exist_ok=True)
            main_py.write_text(SKELETON.format(**s))
            created += 1

    db = lambda n: n.replace("-", "_")
    lines = ["# GENERATED by scripts/generate.py - do not edit by hand.",
             "# `docker compose up` = Phase 1 + infra (Postgres, Kafka, Prometheus, Grafana, Jaeger).",
             "# `--profile phaseN` or `--profile all` adds more services.",
             "x-service: &svc", "  build: {context: ., dockerfile: docker/Dockerfile}", "  restart: unless-stopped",
             "x-env: &env",
             "  JWT_SECRET: dev-secret-change-me",
             "  EVENT_BUS: kafka",
             "  KAFKA_BOOTSTRAP: kafka:9092",
             "  OTEL_EXPORTER_OTLP_ENDPOINT: http://jaeger:4318",
             "services:",
             "  postgres:",
             "    image: postgres:16-alpine",
             "    environment: {POSTGRES_USER: microkart, POSTGRES_PASSWORD: microkart, POSTGRES_DB: postgres}",
             "    volumes: [\"pgdata:/var/lib/postgresql/data\", \"./infra/init-db.sql:/docker-entrypoint-initdb.d/init.sql:ro\"]",
             "    healthcheck: {test: [\"CMD-SHELL\", \"pg_isready -U microkart\"], interval: 5s, timeout: 3s, retries: 20}",
             "  kafka:",
             "    image: apache/kafka:3.8.0",
             "    environment:",
             "      KAFKA_NODE_ID: 1",
             "      KAFKA_PROCESS_ROLES: broker,controller",
             "      KAFKA_LISTENERS: PLAINTEXT://:9092,CONTROLLER://:9093",
             "      KAFKA_ADVERTISED_LISTENERS: PLAINTEXT://kafka:9092",
             "      KAFKA_CONTROLLER_LISTENER_NAMES: CONTROLLER",
             "      KAFKA_LISTENER_SECURITY_PROTOCOL_MAP: CONTROLLER:PLAINTEXT,PLAINTEXT:PLAINTEXT",
             "      KAFKA_CONTROLLER_QUORUM_VOTERS: 1@kafka:9093",
             "      KAFKA_OFFSETS_TOPIC_REPLICATION_FACTOR: 1",
             "      KAFKA_TRANSACTION_STATE_LOG_REPLICATION_FACTOR: 1",
             "      KAFKA_TRANSACTION_STATE_LOG_MIN_ISR: 1",
             "      KAFKA_GROUP_INITIAL_REBALANCE_DELAY_MS: 0",
             "  jaeger:",
             "    image: jaegertracing/all-in-one:1.62.0",
             "    environment: {COLLECTOR_OTLP_ENABLED: \"true\"}",
             "    ports: [\"16686:16686\"]",
             "  prometheus:",
             "    image: prom/prometheus:v2.55.1",
             "    volumes: [\"./infra/prometheus.yml:/etc/prometheus/prometheus.yml:ro\"]",
             "    ports: [\"9090:9090\"]",
             "  grafana:",
             "    image: grafana/grafana:11.3.1",
             "    environment: {GF_AUTH_ANONYMOUS_ENABLED: \"true\", GF_AUTH_ANONYMOUS_ORG_ROLE: Admin}",
             "    volumes: [\"./infra/grafana-datasource.yml:/etc/grafana/provisioning/datasources/ds.yml:ro\"]",
             "    ports: [\"3000:3000\"]"]
    for s in services:
        stateful = s["implemented"] and s["name"] != "api-gateway"
        lines += [f"  {s['name']}:", "    <<: *svc",
                  f"    build: {{context: ., dockerfile: docker/Dockerfile, args: {{SERVICE: {s['name']}}}}}",
                  "    environment:", "      <<: *env", f"      OTEL_SERVICE_NAME: {s['name']}"]
        if stateful:
            lines += [f"      DATABASE_URL: postgresql+psycopg://microkart:microkart@postgres:5432/{db(s['name'])}",
                      "    depends_on:", "      postgres: {condition: service_healthy}",
                      "      kafka: {condition: service_started}"]
        elif s["implemented"]:
            lines += ["    depends_on:", "      kafka: {condition: service_started}"]
        if s["name"] == "api-gateway":
            lines.append('    ports: ["8000:8000"]')
        if s["phase"] > 1:
            lines.append(f'    profiles: ["phase{s["phase"]}", "all"]')
    lines += ["volumes:", "  pgdata: {}"]
    (ROOT / "docker-compose.yml").write_text("\n".join(lines) + "\n")

    infra = ROOT / "infra"
    infra.mkdir(exist_ok=True)
    (infra / "init-db.sql").write_text("-- GENERATED: one database per service\n" +
        "".join(f"CREATE DATABASE {db(s['name'])};\n" for s in services))
    scrape = ["# GENERATED", "global: {scrape_interval: 5s}", "scrape_configs:"]
    for s in services:
        if s["implemented"]:
            scrape.append(f"  - {{job_name: {s['name']}, static_configs: [{{targets: ['{s['name']}:8000']}}]}}")
    (infra / "prometheus.yml").write_text("\n".join(scrape) + "\n")
    (infra / "grafana-datasource.yml").write_text(
        "apiVersion: 1\ndatasources:\n  - {name: Prometheus, type: prometheus, access: proxy, "
        "url: 'http://prometheus:9090', isDefault: true}\n")

    reg = ["# GENERATED by scripts/generate.py - the Helm chart reads this list.", "services:"]
    for s in services:
        stateful = str(s["implemented"] and s["name"] != "api-gateway").lower()
        reg.append(f"  - {{name: {s['name']}, domain: {s['domain']}, phase: {s['phase']}, "
                   f"implemented: {str(s['implemented']).lower()}, stateful: {stateful}}}")
    (ROOT / "charts/microkart/services.yaml").write_text("\n".join(reg) + "\n")

    print(f"{len(services)} services registered, {created} scaffolds created")


if __name__ == "__main__":
    main()
